"""
全局配置文件
"""
import os

# 项目根目录（backend/ 的上级目录）
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# 上传文件存储目录
UPLOAD_DIR = os.path.join(BASE_DIR, "uploads")

# OCR处理后的图片缓存目录
CACHE_DIR = os.path.join(BASE_DIR, "cache")

# 导出Excel存储目录
OUTPUT_DIR = os.path.join(BASE_DIR, "outputs")

# 允许的文件扩展名
ALLOWED_EXTENSIONS = {"pdf", "png", "jpg", "jpeg", "bmp", "tiff", "tif"}

# 最大上传文件大小 (100MB)
MAX_FILE_SIZE = 100 * 1024 * 1024

# PDF转图片DPI (200足够表格文字识别，300太慢)
PDF_DPI = 300

# OCR配置
OCR_LANG = "ch"
OCR_DEVICE = "cpu"
OCR_ENGINE = "onnxruntime"
OCR_WORKERS = 3       # 并行OCR页数
OCR_DET_LIMIT = 960   # 检测边长限制（默认值，保证小文字识别）
OCR_REC_BATCH = 6     # 识别批处理数
OCR_DET_THRESH = 0.3  # 检测阈值（默认值，不过滤浅色文字）
OCR_DET_BOX_THRESH = 0.2  # 检测框阈值（降低，保留更多候选）
OCR_PRE_SCALE_PX = 3000   # 预缩放最大像素（保持高精度，不丢失小文字）

# 表格解析配置
Y_TOLERANCE = 12  # Y坐标容差（像素），用于判断是否同一行
X_TOLERANCE = 20  # X坐标容差（像素），用于判断是否同一列

# Excel表头
EXCEL_HEADERS = [
    "序号", "名称", "单位", "购定价（含税）",
    "税率", "网上询价", "数量", "合计", "备注"
]

# 始终为空的列（OCR不会识别到这些列的数据）
ALWAYS_EMPTY_HEADERS = ["税率", "网上询价"]

# ============================================================
# 内容特征匹配规则（方案3）
# 根据单元格文字内容判断属于哪个字段
# priority 越高越优先匹配
# ============================================================
FIELD_PATTERNS = {
    "序号": {
        "pattern": r"^\d{1,3}$",
        "priority": 10,
        "description": "1-3位纯数字"
    },
    "名称": {
        "pattern": r"^[一-鿿㐀-䶿豈-﫿]{2,}$",
        "priority": 1,
        "blacklist": [
            "合计", "总计", "小计", "本页合计", "日期", "送货单", "送货",
            "收货", "电话", "地址", "联系人", "年月日", "序号", "备注",
            "说明", "单价", "数量", "重量", "金额", "税率", "规格",
            "货物名称", "品名", "商品名称", "单位",
        ],
        "description": "2字以上纯中文（排除关键词）"
    },
    "单位": {
        "pattern": r"^(斤|公斤|kg|KG|Kg|箱|盒|包|袋|瓶|桶|条|只|个|把|件|套|台|吨|升|L|ml|g|两|千克|克|ML|G)$",
        "priority": 9,
        "description": "计量单位"
    },
    "购定价（含税）": {
        "pattern": r"^\d+\.\d{1,2}$",
        "priority": 8,
        "description": "含两位小数的价格（购定价/含税单价）"
    },
    "数量": {
        "pattern": r"^\d+\.?\d*$",
        "priority": 6,
        "description": "数字（可能是数量）"
    },
    "合计": {
        "pattern": r"^\d+\.?\d*$",
        "priority": 3,
        "description": "数字（可能是合计金额）"
    },
    # 备注不再通过内容特征兜底匹配 — 只有 X 坐标落入备注列 + 含数字才填
}

# ============================================================
# 日期识别模式
# 用于从OCR文字中提取日期，按日期分组数据
# ============================================================
DATE_PATTERNS = [
    # "7月1日", "12月31日"
    (r"(\d{1,2})月(\d{1,2})日", lambda m: f"{int(m.group(1))}月{int(m.group(2))}日"),
    # "2024-07-01" 或 "2024/07/01"
    (r"(\d{4})[-/](\d{1,2})[-/](\d{1,2})", lambda m: f"{int(m.group(2))}月{int(m.group(3))}日"),
]

# ============================================================
# 日期范围识别（用于从标题中提取日期列表）
# 例如: "7.1-7.16蔬菜送货单" → ["7月1日", "7月2日", ..., "7月16日"]
# ============================================================
DATE_RANGE_PATTERN = r"(\d{1,2})\.(\d{1,2})\s*[-~～到至]\s*(\d{1,2})\.(\d{1,2})"

